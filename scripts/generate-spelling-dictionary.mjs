// Reproduce: npm install --prefix /tmp/lexicon-tools --ignore-scripts --save-exact
// nspell@2.1.5 dictionary-en@4.0.0 wordnet-db@3.1.14
// Then: node scripts/generate-spelling-dictionary.mjs /tmp/lexicon-tools
// No network access or user input is used by this generator.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const tools=resolve(process.argv[2]||'/tmp/lexicon-tools');
const require=createRequire(tools+'/package.json');
const pinned={nspell:'2.1.5','dictionary-en':'4.0.0','wordnet-db':'3.1.14'};
for(const [name,version]of Object.entries(pinned)){
  const pkg=JSON.parse(readFileSync(`${tools}/node_modules/${name}/package.json`,'utf8'));
  if(pkg.version!==version)throw Error(`Expected ${name}@${version}`);
}
const base=tools+'/node_modules',root=new URL('../',import.meta.url);
const spell=require('nspell')(readFileSync(base+'/dictionary-en/index.aff'),readFileSync(base+'/dictionary-en/index.dic'));
const words=new Set();
const add=value=>{const text=value.toLowerCase().replaceAll('_',' ').replaceAll('’',"'");if(/^[a-z]+(?:[ '-][a-z]+)*$/.test(text))words.add(text);};
// nspell 2.1.5 expands Hunspell affixes; use its accepted forms, not just roots.
for(const word of Object.keys(spell.data))if(spell.correct(word))add(word);
for(const kind of ['noun','verb','adj','adv']){
  for(const line of readFileSync(`${base}/wordnet-db/dict/index.${kind}`,'utf8').split('\n')){
    if(line&&!/^\s/.test(line))add(line.split(' ')[0]);
  }
}
const data=[...words].sort().join('\n')+'\n';
mkdirSync(new URL('assets/',root),{recursive:true});
writeFileSync(new URL('assets/spelling-en-us.txt',root),data);
writeFileSync(new URL('assets/SCOWL-LICENSE.txt',root),readFileSync(base+'/dictionary-en/license'));
writeFileSync(new URL('assets/WordNet-LICENSE.txt',root),readFileSync(base+'/wordnet-db/LICENSE'));
const info={entries:words.size,sha256:createHash('sha256').update(data).digest('hex'),sources:pinned,
  scope:'Modified word-form/phrase index only; no definitions or teaching content. SCOWL US + WordNet 3.1. See assets licenses.',
  upstream:['https://github.com/wooorm/dictionaries/tree/main/dictionaries/en','https://wordnet.princeton.edu/license-and-commercial-use']};
writeFileSync(new URL('spelling-data.mjs',root),'// Generated by scripts/generate-spelling-dictionary.mjs; retain both source licenses.\nexport const dictionaryInfo=Object.freeze('+JSON.stringify(info,null,2)+');\n');
console.log(JSON.stringify({entries:words.size,bytes:Buffer.byteLength(data),sha256:info.sha256}));
